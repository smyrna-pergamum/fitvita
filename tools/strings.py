"""Writes Android string resources from tools/strings/<lang>.json.

en.json is the reference: every other language must have exactly the same keys and the same
format placeholders (%1$d, %2$s, …). Run `python tools/strings.py` after editing a JSON file.
"""
import json
import pathlib
import re
import sys
from xml.sax.saxutils import escape

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "tools/strings"
RES = ROOT / "app/src/main/res"
LANGS = ["en", "tr", "de", "es", "fr", "ru", "ar"]
PH = re.compile(r"%\d+\$[sd]")


def xml(d):
    out = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by tools/strings.py from tools/strings/*.json; edit there. -->", "<resources>"]
    for k, v in d.items():
        t = escape(v).replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
        out.append(f'    <string name="{k}">{t}</string>')
    out.append("</resources>")
    return "\n".join(out) + "\n"


def main():
    ref = json.loads((SRC / "en.json").read_text(encoding="utf-8"))
    errors = []
    for lang in LANGS:
        d = json.loads((SRC / f"{lang}.json").read_text(encoding="utf-8"))
        missing = ref.keys() - d.keys()
        extra = d.keys() - ref.keys()
        if missing or extra:
            errors.append(f"{lang}: missing {sorted(missing)} extra {sorted(extra)}")
        for k in ref.keys() & d.keys():
            if sorted(PH.findall(ref[k])) != sorted(PH.findall(d[k])):
                errors.append(f"{lang}: placeholders differ in {k}")
        ordered = {k: d.get(k, ref[k]) for k in ref}
        folder = RES / ("values" if lang == "en" else f"values-{lang}")
        folder.mkdir(exist_ok=True)
        (folder / "strings.xml").write_text(xml(ordered), encoding="utf-8")
    if errors:
        print("\n".join(errors))
        sys.exit(1)
    print(len(ref), "strings ×", len(LANGS), "languages")


if __name__ == "__main__":
    main()
